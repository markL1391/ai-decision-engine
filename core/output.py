OUTPUT_SCHEMA = """
{
  "summary": "2-3 sentence system assessment",
  "top_priorities": [
    {
      "rank": 1,
      "dimension": "P",
      "action": "Concrete action",
      "rationale": "Reasoning",
      "timeframe": "4-6 weeks"
    }
  ],
  "lever": {
    "dimension": "P",
    "explanation": "Why this dimension has the highest leverage"
  },
  "risk": {
    "level": "high",
    "consequence": "What happens if no action is taken"
  },
  "next_step": {
    "action": "Immediate action",
    "owner": "e.g. Operations Lead",
    "by_when": "e.g. this week"
  },
  "rag_references": ["Source 1", "Source 2"]
}
"""

OUTPUT_INSTRUCTION = f"""
Respond only with one valid JSON object.
Do not add explanations before or after the JSON.
Do not wrap the JSON in Markdown code fences.

Follow this exact schema:

{OUTPUT_SCHEMA}

Allowed values:
- dimension: "T", "P", "R", or "A"
- risk.level: "low", "medium", or "high"
- top_priorities: between 1 and 3 items, ranked sequentially starting at 1
"""


# =============================================================================
# Parsing utilities
# =============================================================================

def parse_llm_output(raw: str) -> AdvisorOutput:
    """
    Parse raw LLM text into a validated AdvisorOutput object.

    Parsing flow:
    1. extract JSON from raw text
    2. decode JSON
    3. validate with Pydantic
    4. raise OutputParseError on failure

    Args:
        raw: Raw text returned by the LLM.

    Returns:
        Validated AdvisorOutput object.
    """
    cleaned = _extract_json(raw)

    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError as exc:
        raise OutputParseError(
            f"Could not parse JSON: {exc}",
            raw_text=raw,
        ) from exc

    try:
        return AdvisorOutput(**data)
    except Exception as exc:
        raise OutputParseError(
            f"Validation failed: {exc}",
            raw_text=raw,
        ) from exc


def _extract_json(text: str) -> str:
    """
    Extract a JSON object from raw LLM output.

    Supports:
    - plain JSON text
    - JSON wrapped in ```json ... ```
    - responses with extra surrounding text

    Args:
        text: Raw LLM response text.

    Returns:
        Extracted JSON string if found, otherwise the stripped raw text.
    """
    code_block_match = re.search(r"```(?:json)?\s*([\s\S]+?)\s*```", text)
    if code_block_match:
        return code_block_match.group(1).strip()

    start = text.find("{")
    end = text.rfind("}")

    if start != -1 and end != -1 and end > start:
        return text[start:end + 1].strip()

    return text.strip()


# =============================================================================
# Error type
# =============================================================================

class OutputParseError(Exception):
    """
    Raised when raw LLM output cannot be parsed or validated.
    """

    def __init__(self, message: str, raw_text: str = "") -> None:
        super().__init__(message)
        self.raw_text = raw_text


# =============================================================================
# Prompt integration helper
# =============================================================================

def inject_output_instruction(system_prompt: str) -> str:
    """
    Append the structured-output instruction to an existing system prompt.

    Args:
        system_prompt: Base system prompt string.

    Returns:
        Extended system prompt including JSON output constraints.
    """
    return system_prompt.rstrip() + "\n\n" + OUTPUT_INSTRUCTION.strip()


def build_executive_summary(result):
    weakest = result["weaknesses"][0] if result["weaknesses"] else "no major constraint"
    strongest = result["strengths"][0] if result["strengths"] else "no strong leverage"

    readiness = result["overall_readiness"]

    return f"""
The current system shows an overall readiness of {readiness:.1f}.

The primary constraint lies in {weakest}, limiting reliable execution and scalability.
At the same time, {strongest} represents a key strength that can be leveraged to accelerate improvements.

Focusing on resolving the constraint while utilizing existing strengths will enable faster and more sustainable system development.
"""