"""
output.py

Structured output parser for the Explainable AI Maturity Assessment System.

This module provides:
- Pydantic models for structured LLM output
- validation rules for consistent response formatting
- parsing utilities for raw LLM responses
- prompt instructions that enforce JSON-only output

It is designed for scenarios where the LLM should return advisory-style
structured responses that can be:
- validated automatically
- stored in a database
- rendered in APIs or dashboards
- converted into readable summaries

This module is especially useful for a future advisory layer or V2 workflow.
"""

from __future__ import annotations

import json
import re
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, field_validator


# =============================================================================
# Enums
# =============================================================================

class RiskLevel(str, Enum):
    """
    Allowed risk levels for structured advisory output.
    """
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class Dimension(str, Enum):
    """
    Allowed maturity dimensions.
    """
    T = "T"
    P = "P"
    R = "R"
    A = "A"


# =============================================================================
# Sub-models
# =============================================================================

class Priority(BaseModel):
    """
    One prioritized recommendation item.
    """
    rank: int = Field(..., ge=1, le=3, description="Priority rank from 1 to 3")
    dimension: Dimension = Field(..., description="Affected maturity dimension")
    action: str = Field(..., min_length=5, description="Concrete action to take")
    rationale: str = Field(..., min_length=5, description="Reason for the action")
    timeframe: Optional[str] = Field(None, description="Optional timeframe, e.g. '4-6 weeks'")


class LeverAnalysis(BaseModel):
    """
    The dimension with the greatest leverage for improvement.
    """
    dimension: Dimension = Field(..., description="Highest-leverage dimension")
    explanation: str = Field(..., description="Why this dimension matters most")


class RiskAssessment(BaseModel):
    """
    Risk outlook if no action is taken.
    """
    level: RiskLevel = Field(..., description="Risk level: low / medium / high")
    consequence: str = Field(..., description="Specific consequence of inaction")


class NextStep(BaseModel):
    """
    One immediate action item.
    """
    action: str = Field(..., description="Immediate next action")
    owner: Optional[str] = Field(None, description="Responsible role or owner")
    by_when: Optional[str] = Field(None, description="Target timing")


# =============================================================================
# Main output model
# =============================================================================

class AdvisorOutput(BaseModel):
    """
    Fully structured advisory output generated by the LLM.

    This object is intended for:
    - API responses
    - dashboard rendering
    - database persistence
    - internal logging
    """
    summary: str = Field(..., description="2-3 sentence system assessment")
    top_priorities: List[Priority] = Field(..., min_length=1, max_length=3)
    lever: LeverAnalysis
    risk: RiskAssessment
    next_step: NextStep
    rag_references: List[str] = Field(default_factory=list, description="Referenced knowledge sources")

    @field_validator("top_priorities")
    @classmethod
    def priorities_must_be_ranked(cls, value: List[Priority]) -> List[Priority]:
        """
        Ensure priorities are ranked sequentially from 1 upward.
        """
        ranks = [p.rank for p in value]
        if sorted(ranks) != list(range(1, len(ranks) + 1)):
            raise ValueError("Top priorities must be ranked sequentially starting at 1.")
        return sorted(value, key=lambda p: p.rank)

    def to_dict(self) -> Dict[str, Any]:
        """
        Convert the validated output to a plain dictionary.
        """
        return self.model_dump()

    def summary_text(self) -> str:
        """
        Convert the structured output into a readable multiline text summary.
        Useful for logs, CLI previews, or UI rendering.
        """
        lines = [
            "── Overall assessment ───────────────────────────────────────",
            self.summary,
            "\n── Top priorities ───────────────────────────────────────────",
        ]

        for priority in self.top_priorities:
            tf = f" ({priority.timeframe})" if priority.timeframe else ""
            lines.append(f"  {priority.rank}. [{priority.dimension.value}] {priority.action}{tf}")
            lines.append(f"     → {priority.rationale}")

        lines += [
            "\n── Highest leverage ─────────────────────────────────────────",
            f"  {self.lever.dimension.value}: {self.lever.explanation}",
            "\n── Risk outlook ─────────────────────────────────────────────",
            f"  Level: {self.risk.level.value.upper()}",
            f"  {self.risk.consequence}",
            "\n── Next step ────────────────────────────────────────────────",
            f"  {self.next_step.action}",
        ]

        if self.next_step.owner:
            lines.append(f"  Owner: {self.next_step.owner}")
        if self.next_step.by_when:
            lines.append(f"  By: {self.next_step.by_when}")

        if self.rag_references:
            lines.append("\n── References ───────────────────────────────────────────────")
            for ref in self.rag_references:
                lines.append(f"  - {ref}")

        return "\n".join(lines)


